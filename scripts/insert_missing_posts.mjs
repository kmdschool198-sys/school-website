async function insertMissing() {
  const postsCol = collection(db, 'posts');
  const existingSnap = await getDocs(postsCol);
  const existingTitles = new Set();
  existingSnap.forEach(d => {
    existingTitles.add(d.data().title);
  });

  for (const post of newPosts) {
    if (existingTitles.has(post.title)) {
      console.log(`Skipping already existing: ${post.title}`);
      continue;
    }
    const docRef = await addDoc(postsCol, post);
    console.log(`Added: [${post.date}] ${post.title} (ID: ${docRef.id})`);
  }
  process.exit(0);
}

insertMissing().catch(console.error);
