/** ตัวเลขคงที่จากข้อความ เพื่อให้ผลลัพธ์ซ้ำเดิมทุกครั้งที่สร้างร่าง */
function seedFrom(text: string): number {
  let hash = 0;
  for (let i = 0; i < text.length; i++) {
    hash = (hash * 31 + text.charCodeAt(i)) >>> 0;
  }
  return hash;
}

function pick<T>(pool: T[], seed: number, offset: number): T {
  return pool[(seed + offset * 7919) % pool.length];
}

export interface HomeroomDraft {
  date: string;
  topic: string;
  problems: string;
  solutions: string;
  suggestions: string;
  hasIssue: boolean;
}

/**
 * สร้างร่างบันทึกของหนึ่งวัน
 * @param issueEvery ใส่ปัญหาเล็กน้อยทุก ๆ กี่วันโดยประมาณ (3 = ราว 1 ใน 3 วัน)
 */
export function draftForDate(classId: string, date: string, issueEvery = 3): HomeroomDraft {
  const seed = seedFrom(`${classId}|${date}`);
  const hasIssue = issueEvery > 0 && seed % issueEvery === 0;

  if (hasIssue) {
    const issue = pick(MILD_ISSUES, seed, 1);
    return {
      date,
      topic: pick(BACKFILL_TOPICS, seed, 2),
      problems: issue.problem,
      solutions: issue.solution,
      suggestions: pick(BACKFILL_SUGGESTIONS, seed, 3),
      hasIssue: true,
    };
  }

  return {
    date,
    topic: pick(BACKFILL_TOPICS, seed, 2),
    problems: pick(POSITIVE_FINDINGS, seed, 4),
    solutions: pick(POSITIVE_ACTIONS, seed, 5),
    suggestions: pick(BACKFILL_SUGGESTIONS, seed, 3),
    hasIssue: false,
  };
}
