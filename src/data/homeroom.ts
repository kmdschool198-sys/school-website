export function homeroomDocId(classId: string, date: string) {
  return `${classId}_${date}`;
}

/** ภาคเรียนจากเดือน: 1 = พ.ค.–ต.ค., 2 = พ.ย.–เม.ย. */
export function termOfDate(iso: string): 1 | 2 {
  const m = Number(iso.slice(5, 7));
  return m >= 5 && m <= 10 ? 1 : 2;
}

/** ปีการศึกษา (พ.ศ.) จากวันที่ — เทอม 2 เดือน ม.ค.–เม.ย. ยังนับเป็นปีการศึกษาก่อนหน้า */
export function academicYearOfDate(iso: string): number {
  const y = Number(iso.slice(0, 4));
  const m = Number(iso.slice(5, 7));
  const beYear = y + 543;
  return m <= 4 ? beYear - 1 : beYear;
}
